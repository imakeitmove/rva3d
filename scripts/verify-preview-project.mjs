import assert from "node:assert/strict";
import fs from "node:fs/promises";
const release = JSON.parse(await fs.readFile(".preview-release.json", "utf8"));
const project = JSON.parse(await fs.readFile(".vercel/project.json", "utf8"));
const targetFlag = process.argv.indexOf("--target");
const expectedTarget = targetFlag >= 0 ? process.argv[targetFlag + 1] : "preview";
assert(["preview", "production"].includes(expectedTarget), "Expected target must be preview or production");
assert.equal(release.destination.target, expectedTarget);
assert.equal(project.projectId, "prj_bZXgUFRiXRpbAur3F4RQOOHxcQCe");
assert.equal(project.orgId, "team_r8laQKfVLK3wUEKlg3AUi4Fa");
assert.equal(project.projectId, release.destination.projectId);
assert.equal(project.orgId, release.destination.orgId);
assert.equal(project.settings.nodeVersion, "22.x", "Review a changed project runtime before packaging; do not change Vercel settings automatically");
console.log({ status: "PASS", projectId: project.projectId, orgId: project.orgId, target: expectedTarget, nodeVersion: project.settings.nodeVersion });
